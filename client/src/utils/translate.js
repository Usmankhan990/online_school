export function t(key) {
  if (!key) return key;
  const lang = getCurrentLanguage();
  if (lang !== 'ur') return key;
  const str = String(key).trim();
  return UI_TRANSLATIONS[str] || DICTIONARY[str] || UI_TRANSLATIONS[key] || DICTIONARY[key] || getUrduPlaceholder(str) || key;
}

function getUrduPlaceholder(text) {
  if (!text) return text;
  const trimmed = text.trim();
  if (DICTIONARY[trimmed]) return DICTIONARY[trimmed];
  if (UI_TRANSLATIONS[trimmed]) return UI_TRANSLATIONS[trimmed];

  if (/^Search\s+(.+)\s+books/i.test(trimmed)) {
    return trimmed.replace(/^Search\s+(.+)\s+books\s+by\s+name\s+or\s+subject\.{0,3}/i, '$1 کتب کو نام یا مضمون سے تلاش کریں...');
  }
  if (/^Option\s+([A-Z0-9])/i.test(trimmed)) {
    return trimmed.replace(/^Option\s+([A-Z0-9])/i, 'آپشن $1');
  }
  if (/^e\.g\./i.test(trimmed)) {
    return trimmed.replace(/^e\.g\.\s*,?\s*/i, 'مثلاً ');
  }
  if (/^Search/i.test(trimmed)) {
    return trimmed.replace(/^Search/i, 'تلاش کریں');
  }
  if (/^Enter/i.test(trimmed)) {
    return trimmed.replace(/^Enter/i, 'درج کریں');
  }
  if (/^Type/i.test(trimmed)) {
    return trimmed.replace(/^Type/i, 'لکھیں');
  }
  return trimmed;
}

export function getCurrentLanguage() {
  const saved = localStorage.getItem('site_lang');
  if (saved) return saved;
  const match = document.cookie.match(/googtrans=([^;]+)/);
  if (match && match[1].includes('/ur')) return 'ur';
  return 'en';
}

function ensureOptions(select) {
  if (!select) return;
  if (!select.querySelector('option[value="en"]')) {
    const optEn = document.createElement('option');
    optEn.value = 'en';
    optEn.textContent = 'English';
    select.appendChild(optEn);
  }
  if (!select.querySelector('option[value="ur"]')) {
    const optUr = document.createElement('option');
    optUr.value = 'ur';
    optUr.textContent = 'Urdu';
    select.appendChild(optUr);
  }
}

export function updateDomAttributes(lang) {
  const isUrdu = lang === 'ur';

  // Translate all input/textarea placeholders
  const elements = document.querySelectorAll('input, textarea');
  elements.forEach(el => {
    if (!el.dataset.origPlaceholder && el.placeholder) {
      el.dataset.origPlaceholder = el.placeholder;
    }

    if (isUrdu) {
      const orig = el.dataset.origPlaceholder || el.placeholder;
      if (orig) {
        el.placeholder = getUrduPlaceholder(orig);
      }
    } else {
      if (el.dataset.origPlaceholder) {
        el.placeholder = el.dataset.origPlaceholder;
      }
    }
  });

  // Set document language attributes
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('data-lang', lang);
}

export function clearGoogleCookies() {
  const host = window.location.hostname;
  const paths = ['/', '/online_school', '/online_school/', window.location.pathname];
  const domains = ['', host, '.' + host];
  if (host.includes('.')) {
    const parts = host.split('.');
    if (parts.length >= 2) {
      domains.push('.' + parts.slice(-2).join('.'));
    }
  }

  domains.forEach(d => {
    paths.forEach(p => {
      const domainAttr = d ? `; domain=${d}` : '';
      const pathAttr = `; path=${p}`;
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC${pathAttr}${domainAttr}`;
      document.cookie = `googtrans=null; expires=Thu, 01 Jan 1970 00:00:00 UTC${pathAttr}${domainAttr}`;
    });
  });
}

export function triggerLanguage(targetLang) {
  updateDomAttributes(targetLang);

  const select = document.querySelector('.goog-te-combo');
  if (select) {
    ensureOptions(select);
    if (targetLang === 'en') {
      select.value = '';
      select.selectedIndex = 0;
      select.dispatchEvent(new Event('change', { bubbles: true }));
      select.dispatchEvent(new Event('input', { bubbles: true }));

      const restoreButtons = document.querySelectorAll('button[id*="restore"], [id*="restore"], .goog-close-link');
      restoreButtons.forEach(btn => {
        try { btn.click(); } catch(e) {}
      });
      const iframes = document.querySelectorAll('iframe.goog-te-banner-frame, iframe');
      iframes.forEach(frame => {
        try {
          const doc = frame.contentDocument || frame.contentWindow?.document;
          doc?.querySelector('button[id*="restore"], [id*="restore"], .goog-close-link')?.click();
        } catch(e) {}
      });
    } else {
      if (select.value !== targetLang) {
        select.value = targetLang;
        select.dispatchEvent(new Event('change', { bubbles: true }));
        select.dispatchEvent(new Event('input', { bubbles: true }));
      }
    }
    return true;
  }
  return false;
}

export function setLanguage(lang) {
  localStorage.setItem('site_lang', lang);

  if (lang === 'en') {
    clearGoogleCookies();
  } else {
    const host = window.location.hostname;
    const target = '/en/ur';
    const domains = ['', host, '.' + host];
    if (host.includes('.')) {
      const parts = host.split('.');
      if (parts.length >= 2) domains.push('.' + parts.slice(-2).join('.'));
    }
    domains.forEach(d => {
      const domainStr = d ? `; domain=${d}` : '';
      document.cookie = `googtrans=${target}; path=/${domainStr}`;
      document.cookie = `googtrans=${target}; path=/online_school${domainStr}`;
    });
  }

  window.dispatchEvent(new CustomEvent('language-changed', { detail: { lang } }));
  updateDomAttributes(lang);
  triggerLanguage(lang);
}

export function toggleLanguage() {
  const current = getCurrentLanguage();
  const next = current === 'ur' ? 'en' : 'ur';
  setLanguage(next);
  return next;
}

// Global DOM Mutation Observer ONLY for updating new input placeholders without recursive Google Translate triggers
let observerInitialized = false;
function initTranslationObserver() {
  if (observerInitialized || typeof window === 'undefined') return;
  observerInitialized = true;

  let timer = null;
  const observer = new MutationObserver(() => {
    const lang = getCurrentLanguage();
    if (lang === 'ur') {
      if (!timer) {
        timer = setTimeout(() => {
          timer = null;
          updateDomAttributes('ur');
        }, 80);
      }
    }
  });

  const attach = () => {
    if (document.body) {
      observer.observe(document.body, { childList: true, subtree: true });
      updateDomAttributes(getCurrentLanguage());
      if (getCurrentLanguage() === 'ur') {
        triggerLanguage('ur');
      }
    }
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', attach);
  } else {
    attach();
  }
}

